IF DB_ID('TicketPremiumFederacionGr06') IS NULL
BEGIN
    CREATE DATABASE TicketPremiumFederacionGr06;
END
GO

USE TicketPremiumFederacionGr06;
GO

IF OBJECT_ID('DETALLE_FACTURA', 'U') IS NOT NULL DROP TABLE DETALLE_FACTURA;
IF OBJECT_ID('FACTURA', 'U') IS NOT NULL DROP TABLE FACTURA;
IF OBJECT_ID('LOCALIDAD_PARTIDO', 'U') IS NOT NULL DROP TABLE LOCALIDAD_PARTIDO;
IF OBJECT_ID('PARTIDO_FUTBOL', 'U') IS NOT NULL DROP TABLE PARTIDO_FUTBOL;
GO

CREATE TABLE PARTIDO_FUTBOL (
    CODIGO INT PRIMARY KEY,
    EQUIPO_LOCAL VARCHAR(100) NOT NULL,
    EQUIPO_VISITA VARCHAR(100) NOT NULL,
    FECHA DATETIME NOT NULL,
    LUGAR VARCHAR(150) NOT NULL
);
GO

CREATE TABLE LOCALIDAD_PARTIDO (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CODIGO_PARTIDO INT NOT NULL,
    CODIGO_LOCALIDAD VARCHAR(50) NOT NULL,
    DISPONIBILIDAD INT NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL,
    CONSTRAINT FK_LOCALIDAD_PARTIDO_PARTIDO
        FOREIGN KEY (CODIGO_PARTIDO) REFERENCES PARTIDO_FUTBOL(CODIGO)
);
GO

CREATE TABLE FACTURA (
    ID_FACTURA INT IDENTITY(1,1) PRIMARY KEY,
    FECHA DATETIME NOT NULL,
    SUBTOTAL DECIMAL(10,2) NOT NULL,
    IVA DECIMAL(10,2) NOT NULL,
    TOTAL DECIMAL(10,2) NOT NULL
);
GO

CREATE TABLE DETALLE_FACTURA (
    ID_DETALLE INT IDENTITY(1,1) PRIMARY KEY,
    ID_FACTURA INT NOT NULL,
    CODIGO_PARTIDO INT NOT NULL,
    LOCALIDAD VARCHAR(50) NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIO_UNITARIO DECIMAL(10,2) NOT NULL,
    TOTAL DECIMAL(10,2) NOT NULL,
    CONSTRAINT FK_DETALLE_FACTURA_FACTURA
        FOREIGN KEY (ID_FACTURA) REFERENCES FACTURA(ID_FACTURA)
);
GO

